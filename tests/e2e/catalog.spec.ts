import { expect, test } from "@playwright/test";
import { loadCurriculum } from "../../src/lib/content/load-curriculum";
const definitions = await loadCurriculum();

test("busca, filtros, currículo e navegação em todas as telas", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const faviconResponse = await page.request.get("/favicon.ico");
  expect(faviconResponse.status()).toBe(200);
  const svgIconResponse = await page.request.get("/icon.svg");
  expect(svgIconResponse.status()).toBe(200);
  await page.goto("/");
  await expect(page.getByRole("heading", { name: /Conhecimento que/ })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Disciplinas do semestre (26.2)", exact: true })).toBeVisible();
  await expect(page.locator(".period-card")).toHaveCount(5);
  await expect(page.locator(".period-section")).toContainText("Complexidade de Algoritmos e Estrutura de Dados");
  await expect(page.locator(".period-section")).toContainText("Desenvolvimento de Softwares para Web");
  await expect(page.locator(".period-section")).toContainText("Engenharia de Requisitos de Softwares");
  await expect(page.locator(".period-section")).toContainText("Sistemas Operacionais");
  await expect(page.locator(".period-section")).toContainText("Gerenciamento de Banco de Dados");
  await expect(page.locator("body")).not.toContainText("APTA");
  await expect(page.locator(".subject-card")).toHaveCount(definitions.length);
  await page.getByRole("button", { name: "Em desenvolvimento", exact: true }).click();
  await expect(page.locator(".subject-card")).toHaveCount(definitions.filter((item) => item.lifecycleStatus === "IN_PROGRESS").length);
  await page.getByRole("button", { name: "Pausada", exact: true }).click();
  await expect(page.locator(".subject-card")).toHaveCount(1);
  await expect(page.locator(".subject-card")).toContainText("Python");
  await expect(page.locator(".subject-card")).toContainText("4 aulas disponíveis");
  await page.getByRole("button", { name: "Todos os estados", exact: true }).click();
  await page.getByRole("button", { name: "Conceituais", exact: true }).click();
  await expect(page.locator(".subject-card")).toHaveCount(definitions.filter((item) => item.category === "THEORETICAL").length);
  await expect(page.getByRole("heading", { name: "Análise de Requisitos", exact: true })).toBeVisible();
  await expect(page.locator(".subject-card").filter({ has: page.getByRole("heading", { name: "Sistemas Operacionais", exact: true }) })).toBeVisible();
  await page.getByRole("button", { name: "Todas as disciplinas" }).click();
  const search = page.getByRole("textbox", { name: "Buscar disciplinas ou tópicos" });
  await search.fill("lacos");
  await expect(page.locator(".subject-card")).toHaveCount(1);
  await expect(page.locator(".subject-card")).toContainText("Python");
  await search.fill("sem-resultado-improvavel");
  await expect(page.getByRole("heading", { name: "Nenhuma disciplina encontrada" })).toBeVisible();
  await page.getByRole("button", { name: "Limpar filtros" }).click();
  await expect(page.locator(".subject-card")).toHaveCount(definitions.length);
  await page.locator(".subject-card").filter({ has: page.getByRole("heading", { name: "Python", exact: true }) }).click();
  await expect(page.getByRole("heading", { name: "Python", exact: true })).toBeVisible();
  await expect(page.locator(".detail-meta")).toContainText("Pausada");
  await expect(page.locator(".detail-meta")).toContainText("4 aulas disponíveis");
  await expect(page.locator(".module-card")).toHaveCount(definitions.find((item) => item.slug === "python")!.modules.length);
  await page.getByRole("link", { name: /Laços de repetição/ }).click();
  await expect(page.getByRole("heading", { name: "Laços de repetição", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Objetivos de aprendizagem" })).toBeVisible();
  await expect(page.getByText("4 quizzes, 3 Parsons", { exact: false })).toBeVisible();
  await page.getByRole("link", { name: "Condicionais Python" }).click();
  await expect(page.getByRole("heading", { name: "Condicionais", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()!.width);
  expect(errors).toEqual([]);
});

test("API pública, recurso ausente e página de evolução", async ({ request, page }) => {
  const response = await request.get("/api/subjects");
  expect(response.ok()).toBe(true);
  expect((await response.json()).data).toHaveLength(definitions.length);
  const missing = await request.get("/api/topics/ausente.topico");
  expect(missing.status()).toBe(404);
  const missingPage = await page.goto("/disciplinas/ausente");
  expect(missingPage?.status()).toBe(404);
  await expect(page.getByRole("heading", { name: "Este caminho ainda não existe." })).toBeVisible();
  await page.getByRole("link", { name: "O caminho do projeto" }).click();
  await expect(page.getByRole("heading", { name: "Levar o estudo com você" })).toBeVisible();
  await page.goto("/disciplinas/sistemas-operacionais");
  await expect(page.getByRole("heading", { name: "Sistemas Operacionais", level: 1, exact: true })).toBeVisible();
  await expect(page.locator(".detail-meta")).toContainText("Em desenvolvimento");
  await expect(page.locator(".detail-meta")).toContainText("1 aula disponível");
  await expect(page.locator(".academic-track-banner")).toContainText("PERÍODO 26.2");
  await page.goto("/disciplinas/redes");
  await expect(page.getByRole("heading", { name: "Redes de Computadores", level: 1, exact: true })).toBeVisible();
  await expect(page.locator(".detail-meta")).toContainText("Conteúdo planejado");
});
